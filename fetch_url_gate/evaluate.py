"""Run the corpus through the text rule and the gate, and through real clients."""

from __future__ import annotations

import csv
import platform
from dataclasses import dataclass
from pathlib import Path

from .baseline import text_rule_allows
from .classify import check_url
from .corpus import Case, benign_cases, hostile_cases, resolver
from .live import LocalServer, clients, curl_version

CLIENT_COLUMNS = ("urllib", "curl")

# Cases whose host is an address, or plain "localhost", can be sent to a server
# on 127.0.0.1 without a DNS lookup beyond the local hosts file.
_LIVE_TARGETS = ("loopback", "unspecified")
_NO_LIVE_GROUPS = ("dns-name", "internal-name", "single-label", "other-scheme")
_LIVE_NAMES = ("localhost", "LOCALHOST")


@dataclass(frozen=True)
class Result:
    case: Case
    text_allows: bool
    gate_allows: bool
    reached: dict | None  # client name -> reached the server; None: not sent

    @property
    def reached_any(self) -> bool:
        return bool(self.reached) and any(self.reached.values())


def _live_candidate(case: Case) -> bool:
    if case.target not in _LIVE_TARGETS or case.group in _NO_LIVE_GROUPS:
        return False
    if case.group == "localhost-name":
        return any(f"//{name}:" in case.url for name in _LIVE_NAMES)
    return True


def run(port: int, live: bool) -> list[Result]:
    available = clients() if live else {}
    results = []
    for case in hostile_cases(port) + benign_cases():
        reached = None
        if live and _live_candidate(case):
            reached = {name: fn(case.url) for name, fn in available.items()}
        results.append(
            Result(case, text_rule_allows(case.url), check_url(case.url, resolver=resolver).allow, reached)
        )
    return results


def _order(items):
    seen = []
    for item in items:
        if item not in seen:
            seen.append(item)
    return seen


def _table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def summary(results: list[Result], live: bool) -> str:
    hostile = [r for r in results if not r.case.expect_allow]
    benign = [r for r in results if r.case.expect_allow]
    out = [
        "# Results",
        "",
        f"Python {platform.python_version()} on {platform.system()} {platform.release()}. "
        "The corpus is generated by rule, so the hostile and benign counts do not depend on a seed. "
        "Only the live server's port changes from run to run.",
        "",
        f"## Hostile URLs ({len(hostile)})",
        "",
        "Every row is a URL that should be denied. A count above zero in a rule's column is a miss.",
        "",
    ]
    rows = []
    for g in _order(r.case.group for r in hostile):
        sub = [r for r in hostile if r.case.group == g]
        rows.append((g, len(sub), sum(r.text_allows for r in sub), sum(r.gate_allows for r in sub)))
    rows.append(("total", len(hostile), sum(r.text_allows for r in hostile), sum(r.gate_allows for r in hostile)))
    out.append(_table(["family", "URLs", "allowed by text rule", "allowed by gate"], rows))
    out += ["", f"## Benign URLs ({len(benign)})", "", "Every row is a URL that should be allowed. A count above zero is an innocent URL blocked.", ""]
    rows = []
    for g in _order(r.case.group for r in benign):
        sub = [r for r in benign if r.case.group == g]
        rows.append((g, len(sub), sum(not r.text_allows for r in sub), sum(not r.gate_allows for r in sub)))
    rows.append(("total", len(benign), sum(not r.text_allows for r in benign), sum(not r.gate_allows for r in benign)))
    out.append(_table(["family", "URLs", "blocked by text rule", "blocked by gate"], rows))
    blocked = [r.case.url for r in benign if not r.text_allows]
    if blocked:
        out += ["", "Blocked by the text rule:", ""] + [f"- `{u}`" for u in blocked]
    if live:
        sent = [r for r in hostile if r.reached is not None]
        names = [n for n in CLIENT_COLUMNS if sent and n in sent[0].reached]
        reached = [r for r in sent if r.reached_any]
        out += [
            "",
            "## Live check",
            "",
            "Each URL below points at a server listening on 127.0.0.1 (the host may also be 0.0.0.0 or localhost). "
            "A request counts as reached when the client gets the server's reply, with proxies off. "
            f"Clients: urllib (Python {platform.python_version()}) and {curl_version()}. "
            "The port is chosen at random on each run.",
            "",
            _table(
                ["URLs sent"] + [f"reached by {n}" for n in names]
                + ["reached by either", "of those, allowed by text rule", "of those, allowed by gate"],
                [[len(sent)] + [sum(r.reached[n] for r in sent) for n in names]
                 + [len(reached), sum(r.text_allows for r in reached), sum(r.gate_allows for r in reached)]],
            ),
            "",
            "Reached, by family:",
            "",
            _table(
                ["family", "sent"] + names + ["either"],
                [
                    [g, sum(r.case.group == g for r in sent)]
                    + [sum(r.case.group == g and r.reached[n] for r in sent) for n in names]
                    + [sum(r.case.group == g for r in reached)]
                    for g in _order(r.case.group for r in sent)
                ],
            ),
            "",
            "Reached by either client but allowed by the text rule:",
            "",
        ] + [f"- `{ascii(r.case.url)}`" for r in reached if r.text_allows]
    return "\n".join(out) + "\n"


def write(results: list[Result], live: bool, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "summary.md").write_text(summary(results, live), encoding="utf-8", newline="\n")
    with (out_dir / "results.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["family", "target", "url", "text_rule_allows", "gate_allows"] + [f"reached_{n}" for n in CLIENT_COLUMNS])
        for r in results:
            cells = [("" if r.reached is None or n not in r.reached else r.reached[n]) for n in CLIENT_COLUMNS]
            writer.writerow([r.case.group, r.case.target, ascii(r.case.url), r.text_allows, r.gate_allows] + cells)


def evaluate(live: bool = True, out_dir: Path | None = None) -> str:
    if live:
        with LocalServer() as server:
            results = run(server.port, True)
    else:
        results = run(8080, False)
    if out_dir is not None:
        write(results, live, out_dir)
    return summary(results, live)
